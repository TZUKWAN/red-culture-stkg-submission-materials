def test_judge_summary_pooling_rows(fixture_env: dict[str, Path]) -> None:
    outdir = fixture_env["tmp"] / "out_judge"
    rst.main(_run_args(fixture_env, outdir))
    rows = _read_csv(outdir / "JUDGE_AGREEMENT_SUMMARY.csv")

    kinds = {row["kind"] for row in rows}
    assert kinds == {"pairwise", "reliability", "leave_one_judge_out"}
    all_rows = [row for row in rows if row["task_type"] == "ALL"]
    assert {row["kind"] for row in all_rows} == {
        "pairwise", "reliability", "leave_one_judge_out"
    }

    def all_value(kind, item, metric):
        return next(
            float(row["value"]) for row in all_rows
            if row["kind"] == kind and row["item"] == item and row["metric"] == metric
        )

    # Unweighted means of the published values (no recomputation).
    assert all_value("pairwise", "A_vs_B", "agreement") == pytest.approx((0.8 + 0.5) / 2)
    assert all_value("pairwise", "A_vs_B", "cohens_kappa") == pytest.approx((0.6 + 0.1) / 2)
    assert all_value("reliability", "", "fleiss_kappa") == pytest.approx((0.2 + 0.4) / 2)
    assert all_value("reliability", "", "krippendorff_alpha_nominal") == pytest.approx(0.4)
    assert all_value("reliability", "", "n_tasks") == pytest.approx(24.0)  # counts sum
    assert all_value("leave_one_judge_out", "removed_A", "stability") == pytest.approx(0.3)

    # Per-task rows are carried through verbatim (reference, not recomputation).
    verbatim = next(
        row for row in rows
        if row["kind"] == "reliability" and row["task_type"] == "t1"
        and row["metric"] == "fleiss_kappa"
    )
    assert float(verbatim["value"]) == 0.2


