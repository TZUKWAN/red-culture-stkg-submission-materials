def _write_points_outputs(points_dir: Path) -> None:
    """Generate the 13-style outputs with the real experiment-13 machinery.

    The fixture rows are round-tripped through CSV first so the rsi helpers
    see exactly what production sees (stringified flag columns).
    """
    points_dir.mkdir(parents=True, exist_ok=True)
    staged = points_dir / "_staged_runs.csv"
    _write_runs(staged, imcr_style=False)
    runs = rst.read_csv(staged)
    groups: dict[tuple[str, str], list[dict]] = defaultdict(list)
    for row in runs:
        groups[(row["method_id"], row["task_type"])].append(row)
    all_points = []
    for key in sorted(groups):
        rows = groups[key]
        if not any(rsi.numeric_confidence(row) is not None for row in rows):
            continue  # production writes no curve without numeric scores
        all_points.extend(rsi.exact_curve(rows, "constrained_selective"))
    fields = sorted({key for row in all_points for key in row})
    _write_csv(points_dir / rst.POINTS_FILE_SUFFIX, all_points, fields)
    goal13_rows = rsi.goal13_metric_rows(groups, "era", None)
    _write_csv(points_dir / rst.GOAL13_FILE_SUFFIX, goal13_rows, list(goal13_rows[0].keys()))


