def _write_csv(path: Path, rows: list[dict], fields: list[str]) -> None:
    with path.open("w", newline="", encoding="utf-8") as handle:
        writer = csv.DictWriter(handle, fieldnames=fields, extrasaction="ignore")
        writer.writeheader()
        writer.writerows(rows)


def _write_runs(path: Path, imcr_style: bool) -> None:
    rows = []
    for row in _fixture_runs():
        new_row = dict(row)
        if imcr_style:
            # Design §2: covered/correct/safe_correct ship as 0 placeholders
            # and are recomputed by the IMCR reference at evaluation time.
            new_row["covered"] = 0
            new_row["correct"] = 0
            new_row["safe_correct"] = 0
        rows.append(new_row)
    _write_csv(path, rows, RUNS_FIELDS)


