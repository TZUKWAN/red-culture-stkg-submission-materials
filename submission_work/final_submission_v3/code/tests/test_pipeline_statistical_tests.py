def _entity_type_rows() -> list[dict]:
    """16 scored samples; errors placed last (Full), first (B1), middle (B2).

    ``correct = prediction == 'Event'`` with gold 'Event' everywhere.
    Full (B12) fails the hard gate on the last two samples; B10 (selective,
    no gate) shares B12's predictions with the gate disabled.  B9 carries a
    two-level agreement confidence (→ too few discrete scores for areas).
    """
    rows = []
    for index in range(N_ET):
        sample_id = f"ET-s{index + 1:02d}"
        confidence = f"{0.95 - 0.01 * index:.12f}"
        specs = [
            ("B12_full_framework", "Place" if index >= 12 else "Event",
             0 if index >= 14 else 1),
            ("B10_selective_no_gate", "Place" if index >= 12 else "Event", 1),
            ("B1_rule_only", "Place" if index < 4 else "Event", 1),
            ("B2_classifier_only", "Place" if 6 <= index <= 9 else "Event", 1),
            ("B9_agreement_gate", "Place" if index < 4 else "Event", 1),
        ]
        for method_id, prediction, gate in specs:
            row = _base_row(sample_id, "entity_type", method_id, METHOD_NAMES[method_id])
            row["gold_label"] = "Event"
            row["prediction"] = prediction
            row["confidence"] = (
                confidence
                if method_id != "B9_agreement_gate"
                else ("1.0" if index % 2 == 0 else "0.0")
            )
            row["correct"] = int(prediction == "Event")
            row["hard_constraint_pass"] = gate
            row["safe_correct"] = int(row["correct"] and gate)
            rows.append(row)
    return rows


def _scope_adjustment_rows() -> list[dict]:
    """12 point-only samples; B12 always predicts AFTER_BETTER (design §4.3).

    Reference: AFTER_BETTER on {0..6}, BEFORE_BETTER on {7..11}.  B3 agrees
    with the reference only on {0,1,2,8}, so the McNemar discordances are
    b = Full correct & B3 wrong = {3,4,5,6} = 4 and
    c = B3 correct & Full wrong = {8} = 1.
    """
    rows = []
    b3_after = {0, 1, 2, 7, 9, 10, 11}  # BEFORE_BETTER elsewhere (incl. 8)
    for index in range(N_SA):
        sample_id = f"SA-s{index + 1:02d}"
        reference = "AFTER_BETTER" if index <= 6 else "BEFORE_BETTER"
        b12_prediction = "AFTER_BETTER"
        b3_prediction = "AFTER_BETTER" if index in b3_after else "BEFORE_BETTER"
        for method_id, prediction in (
            ("B12_full_framework", b12_prediction),
            ("B3_blind_llm", b3_prediction),
        ):
            row = _base_row(sample_id, "scope_adjustment", method_id, METHOD_NAMES[method_id])
            row["prediction"] = prediction
            row["confidence"] = ""  # design §4.3: no graded confidence
            row["correct"] = int(prediction == reference)
            row["safe_correct"] = row["correct"]
            rows.append(row)
    return rows


def _provenance_rows() -> list[dict]:
    """Blind LLM only, 25/100 predictions available, 10 correct (no Full)."""
    rows = []
    for index in range(N_PRV):
        sample_id = f"PRV-s{index + 1:03d}"
        available = index < 25
        row = _base_row(sample_id, "provenance_support", "B3_blind_llm", METHOD_NAMES["B3_blind_llm"])
        row["availability_status"] = "available" if available else "not_available"
        row["prediction"] = "fully_supported" if available else ""
        row["hard_constraint_pass"] = 1 if available else 0
        row["correct"] = int(available and index < 10)
        row["safe_correct"] = row["correct"]
        rows.append(row)
    return rows


