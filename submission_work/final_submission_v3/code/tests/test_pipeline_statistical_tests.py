def _wilson_formula(k: int, n: int) -> tuple[float, float]:
    """Hand-computed Wilson score interval (z = 1 - (1-0.95)/2 quantile)."""
    z = 1.959963984540054
    p = k / n
    denom = 1 + z * z / n
    centre = (p + z * z / (2 * n)) / denom
    half = (z / denom) * math.sqrt(p * (1 - p) / n + z * z / (4 * n * n))
    return max(0.0, centre - half), min(1.0, centre + half)


def test_wilson_table_endpoints_hand_computed(fixture_env: dict[str, Path]) -> None:
    outdir = fixture_env["tmp"] / "out_wilson"
    rst.main(_run_args(fixture_env, outdir))
    rows = _read_csv(outdir / "WILSON_CI_TABLE.csv")

    coverage_rows = [row for row in rows if row["metric"] == "coverage"]
    accuracy_rows = [row for row in rows if row["metric"] == "selective_accuracy"]
    # 8 cells (5 entity_type methods, 2 scope_adjustment, 1 provenance)
    assert len(coverage_rows) == 8 and len(accuracy_rows) == 8

    def cell(rows_, method, task, metric):
        return next(
            row for row in rows_
            if row["method_id"] == method and row["task_type"] == task and row["metric"] == metric
        )

    # Full framework / entity_type: 14 eligible of 16, 12 correct among them.
    row = cell(coverage_rows, "B12_full_framework", "entity_type", "coverage")
    assert int(row["n"]) == 16 and int(row["correct"]) == 14 and int(row["error"]) == 2
    assert float(row["estimate"]) == pytest.approx(14 / 16)
    low, high = _wilson_formula(14, 16)
    assert float(row["ci95_low"]) == pytest.approx(low, abs=1e-12)
    assert float(row["ci95_high"]) == pytest.approx(high, abs=1e-12)

    row = cell(accuracy_rows, "B12_full_framework", "entity_type", "selective_accuracy")
    assert int(row["n"]) == 14 and int(row["correct"]) == 12
    assert float(row["estimate"]) == pytest.approx(12 / 14)
    low, high = _wilson_formula(12, 14)
    assert float(row["ci95_low"]) == pytest.approx(low, abs=1e-12)
    assert float(row["ci95_high"]) == pytest.approx(high, abs=1e-12)

    # Literature anchor: wilson_ci(25, 100) (statsmodels / R prop.test).
    row = cell(coverage_rows, "B3_blind_llm", "provenance_support", "coverage")
    assert int(row["n"]) == 100 and int(row["correct"]) == 25
    assert float(row["ci95_low"]) == pytest.approx(0.17545211362287674, abs=1e-9)
    assert float(row["ci95_high"]) == pytest.approx(0.34304463548061603, abs=1e-9)
    accuracy = cell(accuracy_rows, "B3_blind_llm", "provenance_support", "selective_accuracy")
    assert int(accuracy["n"]) == 25 and int(accuracy["correct"]) == 10
    low, high = _wilson_formula(10, 25)
    assert float(accuracy["ci95_low"]) == pytest.approx(low, abs=1e-12)

    # Point-only cell (scope_adjustment, no confidence by design §4.3):
    # acceptance = prediction available AND hard gate → all 12 rows accepted.
    row = cell(coverage_rows, "B12_full_framework", "scope_adjustment", "coverage")
    assert row["operating_point_mode"] == "point_only"
    assert int(row["n"]) == 12 and int(row["correct"]) == 12
    low, high = _wilson_formula(12, 12)
    assert float(row["ci95_low"]) == pytest.approx(low, abs=1e-12)
    assert float(row["ci95_high"]) == pytest.approx(1.0, abs=1e-12)
    accuracy = cell(accuracy_rows, "B12_full_framework", "scope_adjustment", "selective_accuracy")
    assert int(accuracy["n"]) == 12 and int(accuracy["correct"]) == 7
    assert "point_only_mode" in accuracy["note"]


