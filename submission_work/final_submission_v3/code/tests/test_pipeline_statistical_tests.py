def test_mcnemar_b_c_and_exact_p_value(fixture_env: dict[str, Path]) -> None:
    outdir = fixture_env["tmp"] / "out_mcnemar"
    rst.main(_run_args(fixture_env, outdir))
    rows = _read_csv(outdir / "MCNEMAR_TESTS.csv")

    sa = next(
        row for row in rows
        if row["task_type"] == "scope_adjustment"
        and row["baseline_method_id"] == "B3_blind_llm"
    )
    # b = Full correct & B3 wrong = {s4..s7}; c = B3 correct & Full wrong = {s9}.
    assert int(sa["b_full_correct_baseline_wrong"]) == 4
    assert int(sa["c_full_wrong_baseline_correct"]) == 1
    assert int(sa["n_pairs"]) == 12 and int(sa["n_discordant"]) == 5
    # exact binomial: p = 2 * P(X <= 1; n=5, p=.5) = 2 * 6/32 = 0.375
    assert float(sa["p_value"]) == pytest.approx(0.375, abs=1e-12)
    assert sa["method"] == "exact_binomial"
    assert float(sa["statistic"]) == pytest.approx(1.0)
    assert "AFTER_BETTER" in sa["note"]
    assert int(sa["full_wins"]) == 4 and int(sa["full_losses"]) == 1 and int(sa["ties"]) == 7

    # Entity-type comparison with identical correct flags → no discordant
    # pairs; the row is kept with an explicit note (no silent drop).
    b10 = next(
        row for row in rows
        if row["task_type"] == "entity_type"
        and row["baseline_method_id"] == "B10_selective_no_gate"
    )
    assert int(b10["n_discordant"]) == 0
    assert float(b10["p_value"]) == 1.0
    assert "no discordant pairs" in b10["note"]

    # Hand-check the B1 discordances: b = {s1..s4}, c = {s13..s16}.
    b1 = next(
        row for row in rows
        if row["task_type"] == "entity_type" and row["baseline_method_id"] == "B1_rule_only"
    )
    assert int(b1["b_full_correct_baseline_wrong"]) == 4
    assert int(b1["c_full_wrong_baseline_correct"]) == 4
    assert int(b1["n_pairs"]) == 16
    # provenance_support has no Full rows → no comparison (not silently faked)
    assert not any(row["task_type"] == "provenance_support" for row in rows)


